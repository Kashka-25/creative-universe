// Bakes the guide's authored clips (src/scene/guide/proceduralClips.ts) to
// blender/clips.json, so the Blender character plays exactly the same
// animation as the stand-in. Run with `npm run guide:clips`.
//
// Every bone's rest frame is the character's own axes (+X his left, +Y up,
// +Z towards the camera), in Blender as on the web, so the quaternions and
// positions carry over unchanged.

import { writeFileSync } from 'node:fs';
import { Group, type Object3D, type QuaternionKeyframeTrack, type VectorKeyframeTrack, type NumberKeyframeTrack, Vector3 } from 'three';
import { BONES, guideContract } from '../src/scene/guide/contract';
import { REST } from '../src/scene/guide/rest';
import { buildProceduralClips, type MorphName } from '../src/scene/guide/proceduralClips';

const out = process.argv[2] ?? 'blender/clips.json';
const fps = guideContract.asset.fps;

const bones: Record<string, Object3D> = {};
for (const name of [...BONES.required, ...BONES.optional]) {
  const g = new Group();
  g.name = name;
  g.position.set(...(REST[name] ?? [0, 0, 0]));
  g.userData.rest = g.position.clone();
  bones[name] = g;
}

const morphs: MorphName[] = ['eyesClosed', 'smile', 'grin', 'squint', 'mouthOpen', 'browsUp'];
const clips = buildProceduralClips(bones, { fps, morphMeshes: Object.fromEntries(morphs.map((m) => [m, ['face']])) });

const round = (v: number) => Math.round(v * 1e5) / 1e5;
const data = clips.map((clip) => {
  const frames = Math.round(clip.duration * fps);
  const rot: Record<string, number[][]> = {};
  const loc: Record<string, number[][]> = {};
  const shape: Record<string, number[]> = {};
  for (const track of clip.tracks) {
    const [node, prop] = track.name.split('.');
    const n = track.getValueSize();
    const rows: number[][] = [];
    for (let f = 0; f <= frames; f++) {
      const i = Math.min(f, track.times.length - 1);
      rows.push(Array.from(track.values.slice(i * n, i * n + n), round));
    }
    if (prop === 'quaternion') {
      // three.js stores x, y, z, w; Blender wants w, x, y, z.
      rot[node] = rows.map(([x, y, z, w]) => [w, x, y, z]);
      void (track as QuaternionKeyframeTrack);
    } else if (prop === 'position') {
      const rest = bones[node].userData.rest as Vector3;
      // Blender pose location is the offset from rest.
      loc[node] = rows.map(([x, y, z]) => [round(x - rest.x), round(y - rest.y), round(z - rest.z)]);
      void (track as VectorKeyframeTrack);
    } else if (prop.startsWith('morphTargetInfluences')) {
      const key = prop.slice(prop.indexOf('[') + 1, -1);
      shape[key] = rows.map((r) => r[0]);
      void (track as NumberKeyframeTrack);
    }
  }
  return { name: clip.name, seconds: clip.duration, frames, rot, loc, shape };
});

writeFileSync(out, JSON.stringify({ $comment: 'Generated by scripts/export-guide-clips.ts. Do not edit; edit proceduralClips.ts and re-run npm run guide:clips.', fps, rest: REST, clips: data }));
console.log(`Wrote ${data.length} clips to ${out}: ${data.map((c) => c.name).join(', ')}`);
